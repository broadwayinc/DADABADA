#!/usr/bin/env python3
"""Writes THIRD-PARTY-NOTICES: the license texts of everything compiled into the ddbd binary.

Run from the repository root after changing dependencies, and before a release:
    python3 tools/third_party.py
It reads `cargo metadata`, follows only the dependencies that end up in the binary (not build or
test tools) for the Linux targets we ship, and copies each package's license files from the cargo
registry. The C and C++ libraries bundled by the -sys crates (RocksDB, LZ4, Zstandard) are listed
with their own license files, and so is the JetBrains Mono font that the web admin serves.
"""
import hashlib, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "THIRD-PARTY-NOTICES")
TARGETS = ["x86_64-unknown-linux-gnu", "aarch64-unknown-linux-gnu"]
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|UNLICENSE|NOTICE)([-._].*)?$", re.I)
# license files of the C and C++ code that -sys crates compile in
BUNDLED = {
    "librocksdb-sys": [("RocksDB", "rocksdb/LICENSE.Apache"), ("RocksDB (LevelDB portions)", "rocksdb/LICENSE.leveldb")],
    "lz4-sys": [("LZ4 library", "liblz4/lib/LICENSE")],
    "zstd-sys": [("Zstandard", "zstd/LICENSE")],
}
FONT = ("JetBrains Mono font (served by the web admin)", os.path.join(ROOT, "src/ui/OFL-JetBrainsMono.txt"))


def metadata(target):
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--filter-platform", target],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def shipped(meta):
    """Package ids reachable from the root through normal (non-build, non-dev) dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        pid = todo.pop()
        for d in nodes[pid]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]) and d["pkg"] not in seen:
                seen.add(d["pkg"])
                todo.append(d["pkg"])
    return seen


def main():
    pkgs = {}
    for t in TARGETS:
        meta = metadata(t)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in shipped(meta):
            p = by_id[pid]
            pkgs[(p["name"], p["version"])] = p
    texts = {}  # text hash -> {"text", "label", "users"}
    missing = []

    def add(text, label, user):
        text = text.replace("\r\n", "\n").strip("\n")
        h = hashlib.sha256(re.sub(r"\s+", " ", text).encode()).hexdigest()
        e = texts.setdefault(h, {"text": text, "label": label, "users": []})
        if user not in e["users"]:
            e["users"].append(user)

    rows = []
    for (name, ver), p in sorted(pkgs.items()):
        d = os.path.dirname(p["manifest_path"])
        user = f"{name} {ver}"
        files = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
        for f in files:
            add(open(os.path.join(d, f), encoding="utf-8", errors="replace").read(), f, user)
        for label, rel in BUNDLED.get(name, []):
            path = os.path.join(d, rel)
            if os.path.isfile(path):
                add(open(path, encoding="utf-8", errors="replace").read(), f"{label}: {rel}", f"{label} (in {user})")
            else:
                missing.append(f"{user}: bundled license {rel} not found")
        if not files:
            # no license file in the package: when Apache-2.0 is one of its licenses, we use it under that one
            if "Apache-2.0" in (p.get("license") or ""):
                add(open(os.path.join(ROOT, "LICENSE"), encoding="utf-8").read(), "Apache-2.0", f"{user} (no license file in the package; used under Apache-2.0)")
            else:
                missing.append(f"{user}: no license file in the package ({p.get('license')})")
        rows.append(f"{name} {ver}  |  {p.get('license') or p.get('license_file')}  |  {p.get('repository') or ''}")
    add(open(FONT[1], encoding="utf-8").read(), "OFL-1.1", FONT[0])

    w = []
    w.append("THIRD-PARTY NOTICES FOR DADABADA\n")
    w.append("DADABADA is licensed under the Apache License, Version 2.0 (see LICENSE and NOTICE).")
    w.append("The binary includes the software listed below. Each is used under its own license;")
    w.append("the full license texts and copyright notices follow the list.")
    w.append("Generated by tools/third_party.py from Cargo.lock; do not edit by hand.\n")
    w.append("=" * 78)
    w.append(f"PACKAGES ({len(rows)} Rust crates, the C/C++ libraries they bundle, and one font)")
    w.append("=" * 78)
    w.extend(rows)
    for label, _ in [x for v in BUNDLED.values() for x in v]:
        w.append(f"{label}  |  bundled C/C++ source, see its license below")
    w.append(f"{FONT[0]}  |  OFL-1.1")
    w.append("")
    w.append("=" * 78)
    w.append(f"LICENSE TEXTS ({len(texts)} distinct)")
    w.append("=" * 78)
    for e in sorted(texts.values(), key=lambda e: (e["label"].lower(), e["users"][0])):
        w.append("")
        w.append("-" * 78)
        w.append(f"{e['label']}, used by: {', '.join(e['users'])}")
        w.append("-" * 78)
        w.append(e["text"])
    open(OUT, "w", encoding="utf-8").write("\n".join(w) + "\n")
    print(f"wrote {OUT}: {len(rows)} crates, {len(texts)} distinct license texts, {os.path.getsize(OUT) // 1024} KB")
    for m in missing:
        print("check:", m)
    return 1 if any("bundled" in m for m in missing) else 0


if __name__ == "__main__":
    sys.exit(main())
